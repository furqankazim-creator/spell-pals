# Downloads Noto Emoji PNGs (Apache-2.0, 128px) for every emoji used in the app and writes src/data/emojiImages.ts
import re, io, glob, os, sys, urllib.request, json
files = glob.glob('src/**/*.ts', recursive=True) + glob.glob('src/**/*.tsx', recursive=True) + glob.glob('app/*.tsx') + ['content/words.json']
pat = re.compile(r'(?:[\U0001F1E6-\U0001F1FF]{2}|(?:[©®‼-㊙\U0001F000-\U0001FAFF][️⃣]?(?:‍[©®‼-㊙\U0001F000-\U0001FAFF][️]?)*))')
found = set()
for f in files:
    if f.endswith('emojiImages.ts'): continue
    t = io.open(f, encoding='utf-8').read()
    for m in pat.findall(t):
        if any(ord(c) > 0x2000 for c in m) and not m.isascii():
            cps = [ord(c) for c in m]
            if cps[0] in (0x2014, 0x2019, 0x201c, 0x201d, 0x2190, 0x00b7, 0x21ba, 0x2022, 0x2026): continue
            found.add(m)
def key(e): return '_'.join('%x' % ord(c) for c in e)
def stripfe(e): return ''.join(c for c in e if ord(c) != 0xfe0f)
BASE = 'https://raw.githubusercontent.com/googlefonts/noto-emoji/v2.042/png/128/emoji_u%s.png'
ok, miss = {}, []
for e in sorted(found):
    k = key(stripfe(e))
    out = 'assets/emoji/%s.png' % k
    if not os.path.exists(out):
        data = None
        for cand in (key(e), k):
            try:
                data = urllib.request.urlopen(BASE % cand, timeout=20).read(); break
            except Exception: pass
        if not data: miss.append(e); continue
        open(out, 'wb').write(data)
    ok[stripfe(e)] = k
lines = ['// AUTO-GENERATED by scripts/fetch-emoji.py — Noto Emoji pictures (Apache-2.0).', 'export const EMOJI_IMAGES: Record<string, number> = {']
for e, k in sorted(ok.items(), key=lambda x: x[1]):
    lines.append("  '%s': require('../../assets/emoji/%s.png')," % (e, k))
lines.append('};')
io.open('src/data/emojiImages.ts', 'w', encoding='utf-8').write('\n'.join(lines) + '\n')
print('downloaded', len(ok), 'missing', miss)
